def rel(frm, to):
    """Caminho relativo entre duas páginas do site."""
    up = frm.count("/")
    return "../" * up + to


def demo_block(key, title, desc, store=None):
    st = f' data-store="{store}"' if store else ""
    return (f'<section class="demo" data-demo="{key}"{st} aria-label="{E(title)}"><div class="demo-head"><div><h3>{E(title)}</h3><p>{E(desc)}</p></div>'
            f'<div class="controls"></div></div><div class="demo-body"><p class="small">…</p></div></section>')



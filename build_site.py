def case(L, key, C):
    T = TXT[L]
    path = PAGES[L][key]
    toc = "".join(f'<li><a href="#{a}">{E(b)}</a></li>' for a, b in C["toc"])
    parts = []
    for sid, h2, blocks in C["sections"]:
        parts.append(f'<h2 id="{sid}">{E(h2)}</h2>')
        for b in blocks:
            if b.startswith("@"):
                k = b[1:]
                parts.append(demo_block(k, *C["demos"][k]))
            else:
                parts.append(b)
    body = f"""<div class="wrap">
<header class="case-head"><p class="small"><a href="{E(rel(path, PAGES[L]["home"]))}">{E(T["back"])}</a></p>
<h1>{E(C["title"])}</h1><p class="lead">{E(C["lead"])}</p>
<p class="notice">{E(T["data_notice"])}</p>
<ul class="toc">{toc}</ul></header>
<div class="body">{"".join(parts)}</div>
</div>"""
    return page(L, key, C["title"], C["lead"], body)


